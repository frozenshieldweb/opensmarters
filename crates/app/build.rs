//! Embeds Windows resources into the executable: the application icon
//! (`assets/icon/opensmarters.ico`, so Explorer and the taskbar show it before the window
//! opens) and a VERSIONINFO block (file properties, Task Manager) generated from the crate
//! version.

use std::path::PathBuf;

fn main() {
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed=../../assets/icon/opensmarters.ico");
    if std::env::var("CARGO_CFG_TARGET_OS").as_deref() != Ok("windows") {
        return;
    }
    let (Ok(manifest), Ok(out)) = (
        std::env::var("CARGO_MANIFEST_DIR"),
        std::env::var("OUT_DIR"),
    ) else {
        return;
    };
    let icon = PathBuf::from(&manifest).join("../../assets/icon/opensmarters.ico");
    let icon = icon.to_string_lossy().replace('\\', "\\\\");
    let version = env!("CARGO_PKG_VERSION");
    let mut parts = version
        .split(['.', '-', '+'])
        .map(|p| p.parse::<u16>().unwrap_or(0));
    let (major, minor, patch) = (
        parts.next().unwrap_or(0),
        parts.next().unwrap_or(0),
        parts.next().unwrap_or(0),
    );
    let rc = format!(
        r#"// Generated by build.rs. Do not edit.
1 ICON "{icon}"
1 VERSIONINFO
FILEVERSION {major},{minor},{patch},0
PRODUCTVERSION {major},{minor},{patch},0
FILEFLAGSMASK 0x3fL
FILEFLAGS 0x0L
FILEOS 0x40004L
FILETYPE 0x1L
FILESUBTYPE 0x0L
BEGIN
    BLOCK "StringFileInfo"
    BEGIN
        BLOCK "040904b0"
        BEGIN
            VALUE "CompanyName", "opensmarters contributors"
            VALUE "FileDescription", "opensmarters - secure open-source IPTV player"
            VALUE "FileVersion", "{version}"
            VALUE "InternalName", "opensmarters"
            VALUE "LegalCopyright", "GPL-3.0-or-later"
            VALUE "OriginalFilename", "opensmarters.exe"
            VALUE "ProductName", "opensmarters"
            VALUE "ProductVersion", "{version}"
        END
    END
    BLOCK "VarFileInfo"
    BEGIN
        VALUE "Translation", 0x409, 1200
    END
END
"#
    );
    let rc_path = PathBuf::from(out).join("opensmarters.rc");
    if let Err(e) = std::fs::write(&rc_path, rc) {
        println!("cargo:warning=could not write the resource script: {e}");
        return;
    }
    // A missing resource compiler only costs the exe icon and version info (the window
    // icon is set at runtime), so warn instead of failing the build.
    if let Err(e) = embed_resource::compile(&rc_path, embed_resource::NONE).manifest_optional() {
        println!("cargo:warning=could not embed the exe resources: {e}");
    }
}
